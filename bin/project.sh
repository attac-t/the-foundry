#!/usr/bin/env bash
#
# Writes the doctrine route and the rules into every harness file, from the source of each.
#
# Claude reads `CLAUDE.md`, Codex reads `AGENTS.md`, and a third harness will read a third name. Each
# one written by hand is another truth to keep in step, and the first drift is silent because nothing
# compares them.
#
# So no harness file owns the list. A rule's own title and the sentence under it are the source.
#
# Usage: bin/project.sh [check]
#
# Exit: 0 written or agreeing, 1 a projection drifted, 3 the source could not be read.

set -euo pipefail

readonly RULES=.claude/rules
readonly FORMATTER=bin/tables.awk
readonly OPEN='<!-- rules: generated by bin/project.sh -->'
readonly SHUT='<!-- /rules -->'

readonly DOCTRINE=.foundry/doctrine.md
readonly ROUTE_OPEN='<!-- doctrine: generated by bin/project.sh -->'
readonly ROUTE_SHUT='<!-- /doctrine -->'

harness_files() { printf 'CLAUDE.md\nAGENTS.md\n'; }

# The title and the sentence under it. A rule with no sentence is one nobody can route to, so it is a
# failure to read rather than a row to leave out.
each_rule() {
    for rule in "$RULES"/*.md; do
        [ -f "$rule" ] || continue

        said=$(awk 'NR > 1 && NF { print; exit }' "$rule")
        [ -n "$said" ] || { echo "FAIL — $rule says nothing under its title." >&2; exit 3; }

        printf '%s\t%s\t%s\n' "$(basename "$rule" .md)" "$rule" "${said%.}"
    done
}

# Each harness gets the shape its own file wants. A
# table copied into two files is prose repeated,
# and `repeats` is right to refuse that here.
block() {
    rows=$(rows_for "$1" | canonical)

    # A pipeline that produced nothing wrote both harness files empty and said
    # PASS. `set -e` does not reach inside a substitution, so the emptiness is
    # what gets asked about.
    [ -n "$rows" ] || { echo "FAIL — the rules block came out empty." >&2; exit 3; }

    printf '%s\n%s\n%s\n' "$OPEN" "$rows" "$SHUT"
}

# What a generator emits is what `bin/tables.sh` grades, so it emits the graded
# shape. Leaving that to a later pass turns the tree red the moment somebody
# runs this and forgets the second command.
canonical() { LC_ALL=C awk -f "$FORMATTER"; }

rows_for() {
    [ "$1" = CLAUDE.md ] && printf '| Rule | Owns |\n|---|---|\n'
    each_rule | awk -F'\t' -v table="$([ "$1" = CLAUDE.md ] && echo 1 || echo 0)" '
        table { printf "| [%s](%s) | %s |\n", $1, $2, $3; next }
               { printf "- `%s` — %s\n", $2, $3 }
    '
}

# Where meaning lives, in each harness's own shape. A route and nothing
# more: a harness file that carries a principle is a second owner
# of it, and the doctrine is the first.
route() {
    printf '%s\n' "$ROUTE_OPEN"
    route_for "$1"
    printf '%s\n' "$ROUTE_SHUT"
}

route_for() {
    [ -f "$DOCTRINE" ] || { echo "FAIL — $DOCTRINE is not there to route to." >&2; exit 3; }

    [ "$1" = CLAUDE.md ] && {
        printf '**Read [`%s`](%s) before you decide anything.** It outranks every rule below.\n' \
            "$DOCTRINE" "$DOCTRINE"
        return
    }

    printf -- '- `%s` — read this first. Where a rule disagrees with it, it loses.\n' "$DOCTRINE"
}

# Everything outside the markers is the harness file's own. A file with no markers has nowhere to put
# the list, and guessing where would make this a templating language.
#
# Takes the text rather than a path, because a file gets two blocks
# written into it and the second must read what the first
# produced, not what is still on disk.
replace_in() {
    said=$1; open=$2; shut=$3; fresh=$4

    printf '%s\n' "$said" | grep -qF "$open" \
        || { echo "FAIL — a harness file has no $open block." >&2; exit 3; }

    printf '%s\n' "$said" | awk -v open="$open" -v shut="$shut" -v fresh="$fresh" '
        $0 == open { print fresh; skip = 1; next }
        $0 == shut { skip = 0; next }
        !skip      { print }
    '
}

# Both blocks, in one pass over one file's text.
projected() {
    said=$(cat "$1")
    said=$(replace_in "$said" "$OPEN" "$SHUT" "$(block "$1")")

    replace_in "$said" "$ROUTE_OPEN" "$ROUTE_SHUT" "$(route "$1")"
}

mode=${1:-write}
drifted=0

for file in $(harness_files); do
    [ -f "$file" ] || { echo "FAIL — $file is not there." >&2; exit 3; }

    made=$(projected "$file")

    [ "$mode" = check ] || { printf '%s\n' "$made" > "$file"; continue; }
    [ "$made" = "$(cat "$file")" ] && continue

    echo "  $file has drifted from $RULES or $DOCTRINE"
    drifted=$((drifted + 1))
done

[ "$mode" = check ] || { echo "PASS — projected into $(harness_files | grep -c .) harness files."; exit 0; }
[ "$drifted" -eq 0 ] && { echo "PASS — every harness file matches $RULES and $DOCTRINE."; exit 0; }

echo "FAIL — a harness file was edited by hand. Run bin/project.sh."
exit 1
